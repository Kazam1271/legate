// Regenerates test/fixtures/commands.json from the built SDK.
//
// The fixture pins the JSON the SDK sends to the enclave. Two tests hold it to
// account: the SDK suite asserts the builders still produce it exactly, and
// vela-app/app/sdk_fixture_test.go decodes it into the Go structs with unknown
// fields disallowed and checks every value. Go's decoder otherwise ignores a
// misspelled field silently, leaving the parameter unset instead of failing.
//
// Only regenerate after deliberately changing the wire format, and update the
// Go test's expectations in the same change.
//
// Run: npm run fixtures

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { commands, Side } from '../dist/index.js';
import { FIXTURE_INPUTS as I } from '../test/fixture-inputs.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../test/fixtures/commands.json');

const cases = [
  ['register_strategy', commands.registerStrategy(I.strategyId, {
    allowedTokens: [I.usdc, I.weth],
    maxOrderBase: I.maxOrderBase,
    maxPositionBase: I.maxPositionBase,
  })],
  ['allocate', commands.allocate({ strategyId: I.strategyId, amount: I.allocateAmount, prices: { [I.weth]: I.refPrice } })],
  ['redeem', commands.redeem({ strategyId: I.strategyId, shares: I.redeemShares })],
  ['submit_intent_buy', commands.submitIntent({
    strategyId: I.strategyId, base: I.weth, side: Side.Buy, amount: I.buyAmount, limitPrice: I.limitPrice,
  })],
  ['submit_intent_sell_unconditional', commands.submitIntent({
    strategyId: I.strategyId, base: I.weth, side: Side.Sell, amount: I.sellAmount,
  })],
  ['cancel_intent', commands.cancelIntent(I.intentId)],
  ['close_batch', commands.closeBatch({ base: I.weth, refPrice: I.refPrice, slippageBps: I.slippageBps })],
  ['withdraw_to_destination', commands.withdraw({ token: I.usdc, amount: I.withdrawAmount, destination: I.destination })],
  ['withdraw_to_sender', commands.withdraw({ token: I.usdc, amount: I.withdrawAmount })],
].map(([name, command]) => ({ name, command }));

const fixture = {
  _comment: [
    'Generated by sdk/scripts/write-fixtures.mjs from the SDK command builders.',
    'Pinned by sdk/test/commands.test.mjs (the SDK still produces exactly this) and',
    'vela-app/app/sdk_fixture_test.go (Go decodes it strictly to the intended values).',
  ],
  cases,
};

await writeFile(out, JSON.stringify(fixture, null, 2) + '\n');
console.log(`wrote ${cases.length} cases to ${path.relative(process.cwd(), out)}`);
